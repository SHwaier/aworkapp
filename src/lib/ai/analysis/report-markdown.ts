import { AI_BUZZWORDS } from "./buzzwords";
import { potentialScore } from "./scoring";
import type { AnalysisInsights, AnalysisKeyword, AnalysisRequirement, FormatCheck } from "./types";

/**
 * Turns an analysis into a Markdown brief someone can hand to their own AI
 * assistant along with their resume. Client-safe (no server imports).
 */

export interface ReportForExport {
  score: number | null;
  summary: string;
  resumeVersionName: string;
  completedAt: string | null;
  createdAt: string;
  requirements: (Omit<AnalysisRequirement, "category"> & {
    category?: AnalysisRequirement["category"];
  })[];
  keywords: AnalysisKeyword[];
  suggestions: {
    type: string;
    priority: "high" | "medium" | "low";
    title: string;
    original: string;
    suggestedText: string;
    rationale: string;
    requiresVerification: boolean;
    status: "open" | "done" | "dismissed";
  }[];
  formatChecks: FormatCheck[];
  insights?: AnalysisInsights | null;
}

export interface JobForExport {
  title: string;
  company: string;
  description: string;
}

const TYPE_LABEL: Record<string, string> = {
  rewrite_bullet: "Rewrite a bullet",
  add_keyword: "Add a keyword",
  add_content: "Add content",
  remove_content: "Remove content",
  reorder: "Reorder",
  wording: "Wording",
};

const AREA_LABEL: Record<string, string> = {
  summary: "Summary",
  skills: "Skills",
  experience: "Experience",
  projects: "Projects",
  education: "Education",
  keywords: "Keywords",
  formatting: "Formatting",
};

const STATUS_LABEL = {
  strong: "Strong",
  adequate: "Adequate",
  weak: "Needs work",
  missing: "Missing",
} as const;

const PRIORITY_ORDER = { high: 0, medium: 1, low: 2 } as const;

function scoreLabel(score: number) {
  return score >= 75 ? "Strong match" : score >= 50 ? "Partial match" : "Weak match";
}

/** Escape text for a Markdown table cell. */
function cell(text: string): string {
  return (
    text
      .replace(/\|/g, "\\|")
      .replace(/\s*\n\s*/g, " ")
      .trim() || " "
  );
}

/** Quote text on one line, so it reads as an exact phrase. */
function quote(text: string): string {
  return `"${text.replace(/\s*\n\s*/g, " ").trim()}"`;
}

function cap(s: string) {
  return s.charAt(0).toUpperCase() + s.slice(1);
}

export function reportFileName(job: Pick<JobForExport, "title" | "company">): string {
  const slug = `${job.title} ${job.company}`
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "")
    .slice(0, 60);
  return `resume-match-${slug || "report"}`;
}

export function reportToMarkdown(a: ReportForExport, job: JobForExport): string {
  const out: string[] = [];
  const push = (...lines: string[]) => out.push(...lines);
  const target = job.company ? `${job.title} at ${job.company}` : job.title;
  const date = new Date(a.completedAt || a.createdAt).toISOString().slice(0, 10);
  const insights = a.insights ?? null;
  const score = a.score ?? 0;
  const reachable = potentialScore(a.requirements, 3);

  push(
    `# Resume improvement brief: ${target}`,
    "",
    `Generated by AWorkApp on ${date} from the resume "${a.resumeVersionName}". Give this file to an AI assistant together with your resume and ask it to revise the resume for this job.`,
    "",
    "## Instructions for the AI assistant",
    "",
    "You are revising the attached resume for the job described below. Use this brief as your guide.",
    "",
    "- Use only facts that are in the resume or that the candidate confirms. Never invent employers, job titles, dates, degrees, tools, or numbers.",
    '- Items marked "Confirm first" add something the resume does not show yet. Ask the candidate before including them.',
    "- Where a change needs a detail you do not have (a metric, a team size, a tool), leave a [bracketed placeholder] and list it as a question at the end.",
    "- Write bullets results-first: a specific action verb, what was done and with which tools, then the result (a number, scope, or concrete outcome). Keep each to one or two lines.",
    '- No first-person pronouns, no "responsible for" or "duties included", and no narrative paragraphs.',
    `- Avoid AI-sounding buzzwords: ${AI_BUZZWORDS.join(", ")}. Prefer concrete tool, system, and project names.`,
    "- Show keywords in context, inside bullets that show how a skill was used. Do not stuff keyword lists or copy the job ad's wording verbatim.",
    "- Keep it ATS-friendly: one column, standard section headings (Experience, Education, Skills), no tables, images, or text boxes, and reverse-chronological order.",
    "- Return the full revised resume, then a short list of what you changed and any questions for the candidate.",
    ""
  );

  push(
    "## Match summary",
    "",
    `- Match score: ${score}/100 (${scoreLabel(score)})`,
    ...(reachable > score
      ? [`- Reachable score if the top 3 gaps are fixed: about ${reachable}/100`]
      : []),
    "",
    a.summary,
    ""
  );
  if (insights?.roleSummary) push(`What this role looks for: ${insights.roleSummary}`, "");

  push(
    "## Job requirements",
    "",
    "| Requirement | Importance | Status in resume | Evidence in resume |",
    "| --- | --- | --- | --- |",
    ...a.requirements.map(
      (r) =>
        `| ${cell(r.text)} | ${cap(r.importance)} | ${cap(r.coverage)} | ${cell(r.evidence ? quote(r.evidence) : "Not shown")} |`
    ),
    ""
  );

  const missing = a.keywords
    .filter((k) => !k.inResume)
    .sort((x, y) => (x.importance === y.importance ? 0 : x.importance === "required" ? -1 : 1));
  const present = a.keywords.filter((k) => k.inResume);
  push("## Keywords", "");
  if (missing.length) {
    push(
      "Missing from the resume (add only if true, ideally inside a bullet that shows how it was used):",
      "",
      ...missing.map((k) => `- ${k.term}${k.importance === "required" ? " (required)" : ""}`),
      ""
    );
  }
  if (present.length) push(`Already in the resume: ${present.map((k) => k.term).join(", ")}`, "");

  if (insights?.actionPlan.length) {
    push(
      "## Plan",
      "",
      ...insights.actionPlan.map(
        (s, i) =>
          `${i + 1}. **${s.title}** (${s.impact} impact, ${s.effort} effort). ${s.detail}${s.relatedRequirement ? ` Addresses: ${s.relatedRequirement.replace(/\.+$/, "")}.` : ""}`
      ),
      ""
    );
  }

  const open = a.suggestions
    .filter((s) => s.status === "open")
    .sort((x, y) => PRIORITY_ORDER[x.priority] - PRIORITY_ORDER[y.priority]);
  if (open.length) {
    push("## Specific edits", "");
    open.forEach((s, i) => {
      push(
        `### ${i + 1}. ${s.title}`,
        "",
        `${cap(s.priority)} priority. ${TYPE_LABEL[s.type] ?? s.type}.`,
        ""
      );
      if (s.original) push(`- Current: ${quote(s.original)}`);
      push(`- ${s.original ? "Suggested" : "Change"}: ${quote(s.suggestedText)}`);
      if (s.rationale) push(`- Why: ${s.rationale}`);
      if (s.requiresVerification)
        push("- Confirm first: this adds something the resume does not show yet.");
      push("");
    });
  }

  if (insights?.benchmarks.length) {
    push(
      "## How strong candidates for this role present themselves",
      "",
      "From general hiring knowledge for this kind of role. Templates use [brackets] for details to fill in only with what is true.",
      ""
    );
    for (const b of insights.benchmarks) {
      const area = AREA_LABEL[b.area] ?? b.area;
      const title = b.title.toLowerCase() === area.toLowerCase() ? area : `${area}: ${b.title}`;
      push(
        `### ${title} (${STATUS_LABEL[b.yourStatus]})`,
        "",
        `- Strong candidates usually: ${b.typical}`,
        `- This resume: ${b.gap}`
      );
      if (b.examples.length) push("- Templates:", ...b.examples.map((e) => `  - ${e}`));
      push("");
    }
  }

  const warnings = a.formatChecks.filter((c) => c.status === "warn");
  if (warnings.length) {
    push(
      "## Formatting and writing issues",
      "",
      ...warnings.map((c) => `- ${c.label}: ${c.detail}`),
      ""
    );
  }

  if (job.description.trim()) {
    push(
      "## Job description",
      "",
      "```text",
      job.description.trim().replace(/```/g, "'''"),
      "```",
      ""
    );
  }

  return (
    out
      .join("\n")
      .replace(/\n{3,}/g, "\n\n")
      .trimEnd() + "\n"
  );
}
